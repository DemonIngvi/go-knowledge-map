x:`## Проблема N+1
Код получает список из N сущностей одним запросом, а потом **в цикле делает ещё по запросу на каждую**: 1 + N запросов вместо 1–2. Каждый запрос — сетевой round-trip и работа планировщика, поэтому 100 заказов по 1 мс превращаются в 100 мс.
- Типичные места: ORM с ленивой загрузкой связей, резолверы [[graphql]], цикл с вызовом репозитория внутри.
- **Как увидеть**: число запросов на один HTTP-запрос в трейсе ([[tracing]]) — длинная «лесенка» одинаковых спанов; {{pg_stat_statements}} с огромным числом вызовов одного запроса ([[pg-explain]]).

## Как лечить
- **JOIN** одним запросом, когда нужны связанные строки.
- **Пакетная загрузка**: собрать id и сделать {{WHERE id = ANY($1)}} — один запрос на всю пачку, затем сопоставить в памяти через map ([[maps]]).
- В GraphQL — DataLoader.
- Если данные с другого сервиса — batch-эндпоинт ({{GetUsers(ids)}}) вместо N вызовов {{GetUser}} ([[grpc]]).
- **Batch в pgx** ({{pgx.Batch}}) отправляет несколько запросов за один round-trip ([[pg-go]]).

## Нормализация
Каждый факт хранится в одном месте (третья нормальная форма): нет дублирования, нет аномалий обновления — одно изменение в одной строке. Это **разумное умолчание для OLTP** ([[pg-mvcc]]).

## Денормализация
Осознанное дублирование ради чтения:
- **счётчики и агрегаты** (число комментариев в посте) вместо {{COUNT(*)}} при каждом показе;
- копия часто нужных полей (имя покупателя в заказе — заодно и фиксация на момент покупки);
- jsonb с вложенными данными для чтения целиком ([[pg-toast]]);
- материализованные представления и отдельные модели чтения ([[cqrs-es]]).
**Цена — согласованность копий**: обновлять в той же транзакции (триггер, [[plpgsql]]) или асинхронно с eventual consistency ([[cap]]). Денормализуйте, когда профиль показал проблему, а не заранее ([[kiss]]).`,
