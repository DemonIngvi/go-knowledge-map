x:`Как сервер доставляет события клиенту в реальном времени: уведомления, чаты, статусы заказов, котировки.

## Варианты
- **Polling**: клиент спрашивает раз в N секунд. Просто, но задержка до N секунд и пустые запросы.
- **Long polling**: запрос висит на сервере, пока не появится событие или не истечёт таймаут; затем клиент сразу переподключается. Работает везде, но каждое событие — новый HTTP-запрос.
- **SSE (Server-Sent Events)**: один долгий HTTP-ответ {{text/event-stream}}, сервер пишет события строками. **Только сервер → клиент**, автоматическое переподключение с {{Last-Event-ID}} встроено в браузерный {{EventSource}}. Хорошо работает через HTTP/2 ([[http]]) и прокси.
- **WebSocket**: после HTTP-рукопожатия {{Upgrade}} соединение становится **двусторонним** каналом кадров. Для чатов, совместного редактирования, игр. В Go: coder/websocket (бывший nhooyr), gorilla/websocket.

## Что важно на сервере
- **Каждое соединение держит горутину и память** ([[goroutines]]). Десятки тысяч соединений — нормально для Go, но считайте память и лимиты файловых дескрипторов.
- **Балансировка**: соединения долгие, поэтому новые поды получают нагрузку медленно; при выкатке все клиенты переподключаются разом — нужны [[jitter]] на клиенте и плавный rollout. Прокси должны поддерживать долгие соединения и Upgrade ([[proxies]]), с адекватными idle timeout и пингами ([[tcp|TCP keepalive]]).
- **Рассылка между репликами**: клиент подключён к поду A, событие пришло в под B. Нужна шина: [[redis-pubsub]], [[kafka-core]] или NATS — каждый под подписан и доставляет своим клиентам.
- **Медленный клиент**: буфер отправки ограничен; переполнился — соединение закрывают, а не копят память (backpressure, [[conc-patterns]]).
- Аутентификация при подключении (токен в первом сообщении или cookie), проверка {{Origin}} у WebSocket ([[owasp]]).

## Как выбирать
Только сервер → клиент — **SSE** (проще, переподключение бесплатно). Двусторонний обмен — **WebSocket**. Межсервисный поток — [[grpc-streaming]].`,
